"use client";

import { useState, useEffect } from 'react';
import { 
  Code2, 
  FileText, 
  FolderOpen, 
  GitBranch, 
  Zap, 
  Download, 
  ChevronRight,
  ChevronDown,
  ChevronLeft,
  Plus,
  Trash2,
  RefreshCw,
  Check,
  Sparkles,
  Brain,
  Layout,
  Database,
  Server,
  Maximize2,
  Minimize2,
  X,
  Search,
  Menu,
  Settings,
  Terminal
} from 'lucide-react';
import { EnhancedFileTree } from './EnhancedFileTree';
import { EnhancedCodeEditor } from './EnhancedCodeEditor';
import { EnhancedCanvasControls } from './EnhancedCanvasControls';
import { OpenAIService } from '@/lib/ai/openai-service';
import { RealGitHubHandler } from '@/lib/github/real-handler';
import { EnhancedProjectExporter } from '@/lib/export/enhanced-exporter';

interface EnhancedCanvasPanelProps {
  initialFiles: Record<string, string>;
  onFilesChange: (files: Record<string, string>) => void;
  stack: string;
  database: string;
  gitProvider: string;
  projectName: string;
  session: any;
  fullScreen?: boolean;
  onFullScreenToggle?: () => void;
}

export function EnhancedCanvasPanel({
  initialFiles,
  onFilesChange,
  stack,
  database,
  gitProvider,
  projectName: initialProjectName,
  session,
  fullScreen = false,
  onFullScreenToggle
}: EnhancedCanvasPanelProps) {
  const [files, setFiles] = useState<Record<string, string>>(initialFiles);
  const [activeFile, setActiveFile] = useState<string | null>(Object.keys(initialFiles)[0] || null);
  const [isGenerating, setIsGenerating] = useState(false);
  const [projectName, setProjectName] = useState(initialProjectName);
  const [sidebarCollapsed, setSidebarCollapsed] = useState(false);
  const [rightPanelCollapsed, setRightPanelCollapsed] = useState(false);
  const [aiSuggestions, setAiSuggestions] = useState<string[]>([]);
  const [isFullScreen, setIsFullScreen] = useState(fullScreen);
  const [searchQuery, setSearchQuery] = useState('');
  const [terminalVisible, setTerminalVisible] = useState(false);

  // Initialize services
  const [aiService] = useState(() => new OpenAIService());
  const [projectExporter] = useState(() => new EnhancedProjectExporter());

  // Sync files with parent
  useEffect(() => {
    onFilesChange(files);
  }, [files, onFilesChange]);

  useEffect(() => {
    setIsFullScreen(fullScreen);
  }, [fullScreen]);

  const handleFileSelect = (path: string) => {
    setActiveFile(path);
  };

  const handleFileChange = (path: string, content: string) => {
    const newFiles = { ...files, [path]: content };
    setFiles(newFiles);
  };

  const handleFileDelete = (path: string) => {
    const newFiles = { ...files };
    delete newFiles[path];
    setFiles(newFiles);
    
    if (activeFile === path) {
      setActiveFile(Object.keys(newFiles)[0] || null);
    }
  };

  const getDefaultContent = (path: string): string => {
    const ext = path.split('.').pop()?.toLowerCase();
    switch (ext) {
      case 'tsx':
        return `import React from 'react';
export default function ${path.split('/').pop()?.split('.')[0] || 'Component'}() {
  return (
    <div>
      <h1>New Component</h1>
      <p>Start editing this component</p>
    </div>
  );
}`;
      case 'ts':
        return `// TypeScript file
export const example = "Hello, World!";`;
      default:
        return `// ${path}`;
    }
  };

  const handleFileCreate = (type: 'file' | 'folder', path: string) => {
    if (type === 'file') {
      const content = getDefaultContent(path);
      const newFiles = { ...files, [path]: content };
      setFiles(newFiles);
      setActiveFile(path);
    }
  };

  const handleAIRegenerate = async () => {
    if (!activeFile) {
      console.warn('No file selected');
      return;
    }

    setIsGenerating(true);
    try {
      const result = await aiService.regenerateWithAI({
        filePath: activeFile,
        currentCode: files[activeFile],
        originalCode: files[activeFile],
        changes: ['Improve code quality', 'Add comments', 'Optimize structure'],
        context: { stack, database, feature: 'regeneration' }
      });
      
      const newFiles = { ...files, [activeFile]: result.generatedCode };
      setFiles(newFiles);
      setAiSuggestions(result.suggestions || []);
      
      console.log('AI enhancement successful:', result.explanation);
      
    } catch (error: any) {
      console.error('AI regeneration error:', error);
    } finally {
      setIsGenerating(false);
    }
  };

  const handleExportProject = async () => {
    try {
      await projectExporter.exportAsZip({
        projectName,
        stack,
        database,
        files,
        description: 'Generated by AI Meta Factory'
      });
    } catch (error: any) {
      console.error('Export error:', error);
    }
  };

  const handlePushToGitHub = async () => {
    if (!session?.accessToken) {
      console.warn('No GitHub session found');
      return;
    }

    setIsGenerating(true);
    try {
      const githubHandler = new RealGitHubHandler(session.accessToken);

      const result = await githubHandler.pushToGitHub({
        owner: session.user?.name || 'user',
        repo: projectName,
        commitMessage: 'Initial commit from AI Meta Factory',
        files: Object.entries(files).map(([path, content]) => ({
          path,
          content
        })),
        createRepo: true,
        isPrivate: false
      });

      if (result.success) {
        console.log('GitHub push successful:', result.repoUrl);
      } else {
        console.error('GitHub push failed:', result.error);
      }
    } catch (error: any) {
      console.error('GitHub error:', error);
    } finally {
      setIsGenerating(false);
    }
  };

  const toggleFullScreen = () => {
    const newFullScreen = !isFullScreen;
    setIsFullScreen(newFullScreen);
    if (onFullScreenToggle) {
      onFullScreenToggle();
    }
  };

  // Calculate stats
  const totalLines = Object.values(files).reduce((sum, c) => sum + c.split('\n').length, 0);
  const fileCount = Object.keys(files).length;

  return (
    <div className={`${isFullScreen ? 'fixed inset-0 z-50' : 'h-[calc(100vh-4rem)]'} bg-gradient-to-br from-gray-900 via-gray-950 to-black text-gray-100 flex flex-col overflow-hidden`}>
      {/* Top Bar */}
      <div className="px-6 py-4 border-b border-gray-800/30 bg-gradient-to-r from-gray-900/95 to-gray-950/95 backdrop-blur-xl">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-4">
            <div className="flex items-center gap-3">
              <div className="p-2 bg-gradient-to-br from-blue-500/20 to-purple-600/20 rounded-lg border border-blue-500/30">
                <Layout className="w-5 h-5 text-blue-400" />
              </div>
              <div>
                <h1 className="text-xl font-bold bg-gradient-to-r from-blue-400 via-purple-400 to-pink-400 bg-clip-text text-transparent">
                  Enhanced Canvas
                </h1>
                <p className="text-xs text-gray-400 flex items-center gap-2">
                  <span className="flex items-center gap-1">
                    <Sparkles className="w-3 h-3" />
                    AI-Powered Development Workspace
                  </span>
                </p>
              </div>
            </div>
            
            {/* Stack Badges */}
            <div className="flex gap-2 ml-6">
              <div className="flex items-center gap-2 px-3 py-1.5 bg-blue-500/10 border border-blue-500/20 rounded-lg">
                <Server className="w-4 h-4 text-blue-400" />
                <span className="text-xs font-medium text-blue-300">{stack.toUpperCase()}</span>
              </div>
              <div className="flex items-center gap-2 px-3 py-1.5 bg-green-500/10 border border-green-500/20 rounded-lg">
                <Database className="w-4 h-4 text-green-400" />
                <span className="text-xs font-medium text-green-300">{database.toUpperCase()}</span>
              </div>
              <div className="flex items-center gap-2 px-3 py-1.5 bg-gray-800/50 border border-gray-700 rounded-lg">
                <GitBranch className="w-4 h-4 text-gray-300" />
                <span className="text-xs font-medium text-gray-300">{gitProvider.toUpperCase()}</span>
              </div>
            </div>
          </div>
          
          {/* Right Controls */}
          <div className="flex items-center gap-4">
            {/* Search */}
            <div className="relative">
              <Search className="absolute left-3 top-1/2 transform -translate-y-1/2 w-4 h-4 text-gray-400" />
              <input
                type="text"
                placeholder="Search files..."
                value={searchQuery}
                onChange={(e) => setSearchQuery(e.target.value)}
                className="pl-10 pr-4 py-2 bg-gray-800/50 border border-gray-700 rounded-lg text-sm w-64 focus:outline-none focus:ring-2 focus:ring-blue-500/30 focus:border-blue-500/30"
              />
            </div>
            
            {/* Stats */}
            <div className="hidden md:flex items-center gap-4 text-xs text-gray-400">
              <div className="flex items-center gap-2">
                <FileText className="w-4 h-4 text-blue-400" />
                <span className="font-semibold text-white">{fileCount} files</span>
              </div>
              <div className="w-px h-4 bg-gray-800" />
              <div className="flex items-center gap-2">
                <Code2 className="w-4 h-4 text-green-400" />
                <span className="font-semibold text-white">{totalLines} lines</span>
              </div>
            </div>
            
            {/* Action Buttons */}
            <div className="flex items-center gap-2">
              <button
                onClick={() => setTerminalVisible(!terminalVisible)}
                className="p-2 hover:bg-gray-800/50 rounded-lg transition-colors"
                title="Toggle Terminal"
              >
                <Terminal className="w-4 h-4" />
              </button>
              <button
                onClick={toggleFullScreen}
                className="p-2 hover:bg-gray-800/50 rounded-lg transition-colors"
                title={isFullScreen ? "Exit Full Screen" : "Full Screen"}
              >
                {isFullScreen ? <Minimize2 className="w-4 h-4" /> : <Maximize2 className="w-4 h-4" />}
              </button>
              {isFullScreen && (
                <button
                  onClick={toggleFullScreen}
                  className="p-2 hover:bg-gray-800/50 rounded-lg transition-colors"
                  title="Close"
                >
                  <X className="w-4 h-4" />
                </button>
              )}
            </div>
          </div>
        </div>
      </div>

      {/* Main Content Area - Fills remaining space */}
      <div className="flex-1 flex overflow-hidden">
        {/* Left Sidebar - File Tree */}
        <div className={`${sidebarCollapsed ? 'w-0' : 'w-72'} transition-all duration-300 border-r border-gray-800/50 flex flex-col`}>
          <div className="flex items-center justify-between px-4 py-3 border-b border-gray-800/50">
            <div className="flex items-center gap-2">
              <FolderOpen className="w-5 h-5 text-blue-400" />
              <h3 className="font-semibold text-white">Project Files</h3>
            </div>
            <div className="flex items-center gap-2">
              <button
                onClick={() => handleFileCreate('file', `src/components/NewComponent.tsx`)}
                className="p-1.5 hover:bg-gray-800/50 rounded-lg transition-colors"
                title="New File"
              >
                <Plus className="w-4 h-4" />
              </button>
              <button
                onClick={() => setSidebarCollapsed(!sidebarCollapsed)}
                className="p-1.5 hover:bg-gray-800/50 rounded-lg transition-colors"
              >
                <ChevronLeft className="w-4 h-4" />
              </button>
            </div>
          </div>
          
          <div className="flex-1 overflow-y-auto">
            <EnhancedFileTree
              files={files}
              onFileSelect={handleFileSelect}
              onFileChange={handleFileChange}
              onFileDelete={handleFileDelete}
              onFileCreate={handleFileCreate}
              activeFile={activeFile}
            />
          </div>
        </div>
        
        {/* Center - Code Editor - Takes most space */}
        <div className="flex-1 flex flex-col min-w-0">
          {/* Editor Tabs */}
          <div className="flex items-center border-b border-gray-800/50 bg-gray-900/30">
            <div className="flex-1 flex items-center overflow-x-auto">
              {Object.keys(files).map((filePath) => (
                <div
                  key={filePath}
                  className={`flex items-center gap-2 px-4 py-3 border-r border-gray-800/50 cursor-pointer transition-colors min-w-[200px] ${
                    activeFile === filePath 
                      ? 'bg-gray-800/70 border-b-2 border-blue-500' 
                      : 'hover:bg-gray-800/30'
                  }`}
                  onClick={() => setActiveFile(filePath)}
                >
                  <FileText className="w-4 h-4 text-gray-400" />
                  <span className="text-sm truncate">{filePath.split('/').pop()}</span>
                  <button
                    onClick={(e) => {
                      e.stopPropagation();
                      handleFileDelete(filePath);
                    }}
                    className="ml-auto opacity-0 group-hover:opacity-100 p-1 hover:bg-red-500/20 rounded"
                  >
                    <X className="w-3 h-3" />
                  </button>
                </div>
              ))}
              <button
                onClick={() => handleFileCreate('file', `src/components/NewComponent.tsx`)}
                className="flex items-center gap-2 px-4 py-3 text-gray-400 hover:text-white hover:bg-gray-800/30 transition-colors"
              >
                <Plus className="w-4 h-4" />
                <span className="text-sm">New</span>
              </button>
            </div>
          </div>
          
          {/* Code Editor - Takes remaining vertical space */}
          <div className="flex-1 overflow-hidden">
            <EnhancedCodeEditor
              files={files}
              onFileChange={handleFileChange}
              activeFile={activeFile}
            />
          </div>
          
          {/* Terminal Panel */}
          {terminalVisible && (
            <div className="h-48 border-t border-gray-800/50 bg-gray-950 flex flex-col">
              <div className="px-4 py-2 border-b border-gray-800/50 bg-gray-900/50 flex items-center justify-between">
                <div className="flex items-center gap-2">
                  <Terminal className="w-4 h-4 text-green-400" />
                  <span className="text-sm font-medium">Terminal</span>
                </div>
                <button
                  onClick={() => setTerminalVisible(false)}
                  className="p-1 hover:bg-gray-800/50 rounded"
                >
                  <X className="w-4 h-4" />
                </button>
              </div>
              <div className="flex-1 p-4 font-mono text-sm overflow-auto">
                <div className="text-green-400">$ npm run dev</div>
                <div className="text-gray-400">{"> Next.js development server started"}</div>
                <div className="text-gray-400">{"> Ready on http://localhost:3000"}</div>
                <div className="mt-4">
                  <div className="text-blue-400">$</div>
                  <div className="text-gray-300">_</div>
                </div>
              </div>
            </div>
          )}
          
          {/* Status Bar */}
          <div className="px-4 py-2 border-t border-gray-800/50 bg-gray-900/30 flex items-center justify-between text-xs">
            <div className="flex items-center gap-4 text-gray-400">
              <div className="flex items-center gap-2">
                <Brain className="w-3 h-3 text-purple-400" />
                <span>AI Ready</span>
              </div>
              <div className="w-px h-4 bg-gray-800" />
              <div className="flex items-center gap-2">
                <Check className="w-3 h-3 text-green-400" />
                <span>No errors</span>
              </div>
              <div className="w-px h-4 bg-gray-800" />
              <div className="flex items-center gap-2">
                <span className="text-gray-500">UTF-8</span>
                <span className="text-gray-500">•</span>
                <span className="text-gray-500">LF</span>
                <span className="text-gray-500">•</span>
                <span className="text-gray-500">TypeScript</span>
              </div>
            </div>
            <div className="flex items-center gap-3">
              <button
                onClick={() => setSidebarCollapsed(!sidebarCollapsed)}
                className="p-1.5 hover:bg-gray-800/50 rounded-lg transition-colors"
              >
                <Menu className="w-4 h-4" />
              </button>
              <button
                onClick={handleAIRegenerate}
                disabled={isGenerating || !activeFile}
                className={`flex items-center gap-2 px-3 py-1.5 rounded-lg transition-all ${
                  isGenerating 
                    ? 'bg-gradient-to-r from-purple-500/30 to-pink-500/30 border border-purple-500/30 cursor-wait' 
                    : 'bg-gradient-to-r from-purple-500 to-pink-500 hover:from-purple-600 hover:to-pink-600'
                }`}
              >
                {isGenerating ? (
                  <RefreshCw className="w-4 h-4 animate-spin" />
                ) : (
                  <Zap className="w-4 h-4" />
                )}
                <span className="text-xs font-medium">
                  {isGenerating ? 'AI Working...' : 'AI Enhance'}
                </span>
              </button>
              <button
                onClick={() => setRightPanelCollapsed(!rightPanelCollapsed)}
                className="p-1.5 hover:bg-gray-800/50 rounded-lg transition-colors"
              >
                <Settings className="w-4 h-4" />
              </button>
            </div>
          </div>
        </div>
        
        {/* Right Panel - Controls & AI */}
        <div className={`${rightPanelCollapsed ? 'w-0' : 'w-96'} transition-all duration-300 border-l border-gray-800/50`}>
          <EnhancedCanvasControls
            onAIRegenerate={handleAIRegenerate}
            onExportProject={handleExportProject}
            onPushToGitHub={handlePushToGitHub}
            isGenerating={isGenerating}
            projectName={projectName}
            onProjectNameChange={setProjectName}
            stack={stack}
            onStackChange={() => {}}
            database={database}
            onDatabaseChange={() => {}}
            gitProvider={gitProvider}
            onGitProviderChange={() => {}}
            session={session}
          />
        </div>
      </div>

      {/* AI Suggestions Bar */}
      {aiSuggestions.length > 0 && (
        <div className="border-t border-gray-800/50 bg-gradient-to-r from-purple-900/20 to-pink-900/20">
          <div className="px-6 py-3">
            <div className="flex items-center gap-3">
              <Sparkles className="w-4 h-4 text-purple-400 animate-pulse" />
              <h3 className="font-semibold text-white">AI Suggestions</h3>
              <div className="flex-1 h-px bg-gradient-to-r from-purple-500/30 to-transparent" />
              <button 
                onClick={() => setAiSuggestions([])}
                className="text-xs text-gray-400 hover:text-white"
              >
                Dismiss
              </button>
            </div>
            <div className="flex flex-wrap gap-2 mt-2">
              {aiSuggestions.slice(0, 6).map((suggestion, index) => (
                <div 
                  key={index}
                  className="px-3 py-1.5 bg-gray-800/70 border border-gray-700/70 rounded-lg text-xs hover:bg-gray-800/90 cursor-pointer transition-colors"
                >
                  {suggestion}
                </div>
              ))}
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
